const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const root = path.join(__dirname, '..');
const outFile = path.join(root, 'src', 'lib', 'emailInlineAssetsData.js');

const assets = [
  { id: 'cu-logo-light', file: 'public/china-unique-logo-cropped.png', width: 440 },
  { id: 'cu-logo-dark', file: 'public/china-unique-logo-dark.png', width: 440 },
  { id: 'cu-facebook', file: 'public/email-icons/facebook-green.png', width: 96 },
  { id: 'cu-instagram', file: 'public/email-icons/instagram-green.png', width: 96 },
  { id: 'cu-whatsapp', file: 'public/email-icons/whatsapp-green.png', width: 96 },
  { id: 'cu-globe', file: 'public/email-icons/globe-green.png', width: 96 },
  { id: 'cu-email', file: 'public/email-icons/email-white.png', width: 96 },
  { id: 'cu-phone', file: 'public/email-icons/phone-white.png', width: 96 },
  { id: 'cu-chat', file: 'public/email-icons/chat-white.png', width: 96 },
  { id: 'cu-zigzag-white', file: 'public/email-icons/zigzag-to-white.png', width: 600 },
  { id: 'cu-zigzag-green', file: 'public/email-icons/zigzag-to-green.png', width: 600 },
];

async function run() {
  const records = [];
  for (const asset of assets) {
    const input = path.join(root, asset.file);
    const png = await sharp(input).resize({ width: asset.width, withoutEnlargement: true }).png().toBuffer();
    records.push({
      id: asset.id,
      filename: path.basename(asset.file),
      content: png.toString('base64'),
    });
  }

  const body = records.map((record) => `  ${JSON.stringify(record.id)}: {
    filename: ${JSON.stringify(record.filename)},
    content: ${JSON.stringify(record.content)},
  }`).join(',\n');

  const source = `/* Auto-generated by scripts/generate-email-inline-assets.js — do not edit by hand. */\nexport const EMAIL_INLINE_ASSETS = {\n${body}\n};\n`;
  fs.writeFileSync(outFile, source);
  console.log('Wrote', outFile, 'bytes', source.length);
}

run().catch((error) => {
  console.error(error);
  process.exit(1);
});
